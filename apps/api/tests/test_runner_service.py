@pytest.fixture
def runner_stack(store, materials, tls_materials, tmp_path):
    if os.environ.get("PRIVACYTRACE_RUNNER_TESTS") != "1":
        pytest.skip("Opt-in actual mTLS + PostgreSQL + Docker Runner component acceptance")
    assert os.name == "posix", "Actual dedicated Linux Docker runner required"
    assert os.environ.get("PRIVACYTRACE_DOCKER_TESTS") == "1", "Actual Docker acceptance required"
    api, intake, draft, path, _ = materials
    apk(path)
    draft["apk_sha256"] = hashlib.sha256(path.read_bytes()).hexdigest()
    lease = execution(store, intake, draft)
    image = command(
        [*docker_prefix(), "image", "inspect", "privacytrace-worker:s1", "--format", "{{.Id}}"]
    ).strip()
    tls = tls_materials
    gateway = create_gateway(
        store, ("127.0.0.1", 0), tls["server"], [tls["other_fingerprint"]], api
    )
    with serving(gateway):
        gateway_client = PrivateClient(
            "https://127.0.0.1:" + str(gateway.server_port), tls["other"], timeout=5
        )
        runner = Runner(RunnerConfig(store.instance_id, image, tmp_path / "runner"), gateway_client)
        server = create_runner_server(
            runner, ("127.0.0.1", 0), tls["other"], [tls["client_fingerprint"]]
        )
        try:
            with serving(server):
                remote = PrivateClient(
                    "https://127.0.0.1:" + str(server.server_port), tls["client"], timeout=30
                )
                client = RunnerClient(store, remote, image, api)
                yield client, runner, draft, path, lease, gateway
        finally:
            runner.close()


def test_actual_metadata_and_scan_use_same_fixed_image_and_inspected_isolation(runner_stack):
    client, runner, draft, path, lease, _ = runner_stack
    metadata = client.inspect_metadata(path)
    assert metadata["package_file"]["sha256"] == draft["apk_sha256"]
    scanned = client.scanner(draft, lease)(path)
    assert scanned["apk_sha256"] == draft["apk_sha256"]
    assert scanned["package_name"] == "org.privacytrace.fixture"
    proof = json.loads(scanned["tools"]["runner_receipt"])
    assert proof["image_id"] == runner.config.image_id
    assert proof["user"] == "65534:65534" and proof["container_created"]
    assert proof["isolation"]["NetworkMode"] == "none" and proof["isolation"]["ReadonlyRootfs"]
    assert proof["cleanup_verified"] and proof["input_removed"]
    assert not list(runner.operations.iterdir())
    assert path.exists(), "Official input remains retained until explicit user deletion"
    assert str(runner.root) not in json.dumps(scanned)


def test_exact_rpc_replay_returns_same_result_without_creating_second_container(runner_stack):
    client, runner, draft, path, lease, _ = runner_stack
    file = client.materials.register(path, draft_id=draft["id"], lease=lease)
    value = {
        "version": 1,
        "operation": "scan",
        "request_id": str(uuid4()),
        "instance_id": lease.instance_id,
        "scope_id": lease.job_id,
        "owner": str(lease.owner),
        "fence": lease.fence,
        "package_set": False,
        "files": [file],
    }
    first = client._response(value)
    second = client._response(value)
    assert second == first
    with runner._database() as conn:
        assert conn.execute("SELECT count(*) FROM operations").fetchone()[0] == 1
    assert not list(runner.operations.iterdir())
    for change in [{"image": "untrusted"}, {"path": "/host"}, {"url": "https://evil"}]:
        with pytest.raises(PermissionError):
            client.remote.json("/v1/run", data={**value, **change})


