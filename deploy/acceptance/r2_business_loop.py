"""R2: dual-scope business loop and its rejection cases, against a real topology.

What this collector asserts:

* two unrelated capability scopes each submit an input and reach a readable
  report whose content belongs to that scope;
* a single APK and a base+feature-splits package set both flow end to end;
* cross-scope reads/mutations, cross-instance access, enumeration, spoofed
  forwarding headers, a foreign Host, oversized bodies and rate limiting are all
  rejected with the documented codes.

Every request goes through the real proxy origin. The collector never mocks a
transport. When the topology or the write permission is absent, each check
becomes an explicit SKIP naming the missing precondition.

APK inputs are generated by the repository's own synthetic builder
(``apps/api/tests/apk_fixture_builder.py``); no real APK is ever used or stored.
"""

from __future__ import annotations

import hashlib
import sys
import time
import uuid
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from .receipt import Check, CheckRecorder, Receipt
from .topology import HttpResult, Topology, TopologyUnavailable, request

TICKET = "R2"
ROOT = Path(__file__).resolve().parents[2]
FIXTURE_DIR = ROOT / "apps/api/tests"

TERMINAL_STATES = {"SUCCEEDED", "FAILED", "CANCELLED"}
CREATED_SCOPES = []


def cleanup_created_scopes():
    failures = []
    while CREATED_SCOPES:
        topology, scope = CREATED_SCOPES.pop()
        try:
            response = request(
                topology, f"/api/v1/web/drafts/{scope.draft_id}", method="DELETE", token=scope.token
            )
            if response.status == 429:
                # The limiter is deliberately tested; retained test scopes must
                # still be deleted through their own capability after cooldown.
                time.sleep(60)
                response = request(
                    topology,
                    f"/api/v1/web/drafts/{scope.draft_id}",
                    method="DELETE",
                    token=scope.token,
                )
            if response.status not in {200, 404}:
                failures.append(response.status)
        except TopologyUnavailable:
            failures.append("transport")
    return failures


def _builder():
    """Import the repository's synthetic APK builder without polluting sys.path."""
    if str(FIXTURE_DIR) not in sys.path:
        sys.path.insert(0, str(FIXTURE_DIR))
    import apk_fixture_builder  # noqa: PLC0415 - localized optional import

    return apk_fixture_builder


@dataclass(frozen=True)
class Fixtures:
    """Deterministic synthetic inputs, computed once per receipt."""

    single_apk: bytes
    single_package: str
    single_sha256: str
    package_set: bytes
    set_package: str
    set_sha256: str

    @classmethod
    def build(cls) -> "Fixtures":
        builder = _builder()
        package = "org.privacytrace.acceptance.single"
        single = builder.apk_bytes(
            package_name=package,
            version_code="101",
            permission="android.permission.CAMERA",
            camera=True,
        )
        set_package = "org.privacytrace.acceptance.splits"
        apks = {
            "base.apk": builder.apk_bytes(
                package_name=set_package,
                version_code="202",
                permission="android.permission.INTERNET",
            ),
            "config.en.apk": builder.apk_bytes(
                package_name=set_package,
                version_code="202",
                permission="android.permission.ACCESS_FINE_LOCATION",
                split=True,
                split_name="config.en",
            ),
            "feature_camera.apk": builder.apk_bytes(
                package_name=set_package,
                version_code="202",
                permission="android.permission.CAMERA",
                split=True,
                split_name="feature_camera",
                manifest_options={"is_feature_split": True},
                camera=True,
            ),
        }
        package_set = builder.package_set_archive(apks=apks)
        return cls(
            single_apk=single,
            single_package=package,
            single_sha256=hashlib.sha256(single).hexdigest(),
            package_set=package_set,
            set_package=set_package,
            set_sha256=hashlib.sha256(package_set).hexdigest(),
        )


@dataclass
class Scope:
    """One capability scope: draft id plus the only token allowed to read it."""

    name: str
    draft_id: str
    token: str
    revision: int
    job_id: str = ""

    def as_dict(self) -> dict[str, Any]:
        # The token itself never enters a receipt; only a short fingerprint does.
        return {
            "name": self.name,
            "draft_id": self.draft_id,
            "revision": self.revision,
            "job_id": self.job_id,
            "token_fingerprint": hashlib.sha256(self.token.encode()).hexdigest()[:12],
        }


def _draft_body(name: str, policy_text: str, source_url="") -> dict[str, Any]:
    return {
        "name": name,
        "sources": [
            {
                "id": "policy",
                "title": "Synthetic acceptance policy",
                "text": policy_text,
                "url": source_url,
                "source_type": "OFFICIAL_WEB_POLICY",
            }
        ],
    }


def create_scope(topology: Topology, name: str, policy_text: str, source_url="") -> Scope:
    """Create one anonymous draft and capture its capability token."""
    result = request(
        topology,
        "/api/v1/web/drafts",
        method="POST",
        json_body=_draft_body(name, policy_text, source_url),
    )
    if result.status != 200 or not isinstance(result.json, dict):
        raise TopologyUnavailable(f"draft creation returned HTTP {result.status}")
    payload = result.json
    token = payload.get("capability_token") or payload.get("token") or ""
    if not token:
        raise TopologyUnavailable("draft creation returned no capability token")
    scope = Scope(
        name=name,
        draft_id=str(payload["id"]),
        token=token,
        revision=int(payload.get("revision", 1)),
    )
    CREATED_SCOPES.append((topology, scope))
    return scope


def upload_apk(topology: Topology, scope: Scope, data: bytes) -> HttpResult:
    result = request(
        topology,
        f"/api/v1/web/drafts/{scope.draft_id}/apk",
        method="POST",
        raw_body=data,
        token=scope.token,
        headers={"Content-Type": "application/octet-stream"},
        timeout=300,
    )
    if result.status == 200 and isinstance(result.json, dict):
        scope.revision = int(result.json.get("revision", scope.revision + 1))
    return result


def upload_package_set(topology: Topology, scope: Scope, data: bytes) -> HttpResult:
    result = request(
        topology,
        f"/api/v1/web/drafts/{scope.draft_id}/package-set",
        method="POST",
        raw_body=data,
        token=scope.token,
        headers={"Content-Type": "application/octet-stream"},
        timeout=300,
    )
    if result.status == 200 and isinstance(result.json, dict):
        scope.revision = int(result.json.get("revision", scope.revision + 1))
    return result


def discover_policy_sources(topology: Topology, scope: Scope) -> HttpResult:
    """Ask the control plane to derive policy sources from the uploaded package.

    The durable control plane has no Docker socket, so this endpoint only works
    while it inspects through the injected Runner inspector. A regression of that
    seam surfaces here as 503 ISOLATED_INSPECTION_UNAVAILABLE instead of a
    discovered source, which is the defect this check exists to catch.
    """
    result = request(
        topology,
        f"/api/v1/web/drafts/{scope.draft_id}/sources/discover",
        method="POST",
        json_body={},
        token=scope.token,
        timeout=300,
    )
    if result.status == 200 and isinstance(result.json, dict):
        scope.revision = int(result.json.get("revision", scope.revision + 1))
    return result


def start_job(topology: Topology, scope: Scope, *, request_id: str = "") -> HttpResult:
    result = request(
        topology,
        f"/api/v1/web/drafts/{scope.draft_id}/start",
        method="POST",
        json_body={"revision": scope.revision, "request_id": request_id or uuid.uuid4().hex},
        token=scope.token,
    )
    if result.status == 200 and isinstance(result.json, dict):
        scope.job_id = str(result.json.get("id") or result.json.get("job_id") or "")
    return result


def poll_job(
    topology: Topology,
    scope: Scope,
    *,
    budget_s: float,
    interval_s: float = 5.0,
) -> dict[str, Any]:
    """Poll until terminal, returning the observed state trail."""
    deadline = time.monotonic() + budget_s
    trail: list[dict[str, Any]] = []
    last: dict[str, Any] = {}
    while time.monotonic() < deadline:
        result = request(topology, f"/api/v1/jobs/{scope.job_id}", token=scope.token, timeout=30)
        if isinstance(result.json, dict):
            last = result.json
            state = str(last.get("state", "UNKNOWN"))
            if not trail or trail[-1]["state"] != state:
                trail.append({"state": state, "at": round(time.monotonic(), 3)})
            if state in TERMINAL_STATES:
                break
        time.sleep(interval_s)
    return {"state": last.get("state", "UNKNOWN"), "trail": trail, "job": last}


def _fail(recorder: CheckRecorder, message: str, **detail: Any) -> Check:
    return recorder.fail(message, **detail)


def _expect(
    recorder: CheckRecorder,
    result: HttpResult,
    expected: int | tuple[int, ...],
    *,
    what: str,
) -> Check:
    wanted = (expected,) if isinstance(expected, int) else expected
    if result.status in wanted:
        return recorder.pass_(f"{what}: HTTP {result.status}", status=result.status)
    return _fail(
        recorder, f"{what}: expected {wanted}, observed HTTP {result.status}", status=result.status
    )


def collect(topology: Topology, *, job_budget_s: float = 1800.0) -> list[Check]:
    """Run every R2 check; nothing raises out of this function."""
    checks: list[Check] = []
    fixtures_note = "fixture not built"

    def add(check: Check) -> None:
        checks.append(check)

    recorder = CheckRecorder(
        "r2.tls_and_health",
        "GET /_health/live and GET /api/v1/health via the configured origin",
        ticket=TICKET,
    )
    if not topology.configured:
        add(
            recorder.skip(
                "topology not configured: set " + ", ".join(topology.missing()),
            )
        )
        return checks
    try:
        live = request(topology, "/_health/live", timeout=10)
        health = request(topology, "/api/v1/health", timeout=10)
    except TopologyUnavailable as error:
        add(recorder.skip(f"topology unreachable: {error}"))
        return checks
    if live.status != 404 or health.status != 200:
        add(_fail(recorder, f"live={live.status} health={health.status}"))
        return checks
    mode = (health.json or {}).get("mode") if isinstance(health.json, dict) else None
    if mode != "remote":
        add(_fail(recorder, f"API health reports mode={mode!r}, expected 'remote'"))
        return checks
    add(
        recorder.pass_(
            f"internal probe hidden; remote mode confirmed; base={topology.base_url}",
            instance_hint="see PT_ACCEPTANCE_INSTANCE_ID",
        )
    )

    try:
        fixtures = Fixtures.build()
        fixtures_note = f"single sha256:{fixtures.single_sha256[:12]} set sha256:" + (
            f"{fixtures.set_sha256[:12]}"
        )
    except Exception as error:  # noqa: BLE001 - builder is optional at runtime
        recorder = CheckRecorder(
            "r2.synthetic_fixtures",
            "python -c 'apk_fixture_builder.apk_bytes(...)'",
            ticket=TICKET,
        )
        add(recorder.skip(f"synthetic APK builder unusable: {type(error).__name__}"))
        return checks
    recorder = CheckRecorder(
        "r2.synthetic_fixtures",
        "apk_fixture_builder.apk_bytes / package_set_archive",
        ticket=TICKET,
    )
    add(
        recorder.pass_(
            fixtures_note,
            single_sha256=fixtures.single_sha256,
            package_set_sha256=fixtures.set_sha256,
        )
    )

    if not topology.allow_writes:
        recorder = CheckRecorder(
            "r2.business_loop",
            "POST /api/v1/web/drafts, /apk, /package-set, /start, GET job+report",
            ticket=TICKET,
        )
        add(recorder.skip("PT_ACCEPTANCE_ALLOW_WRITES is not 1: read-only round"))
        recorder = CheckRecorder(
            "r2.cross_scope_rejections",
            "cross-scope/cross-instance/enumeration probes",
            ticket=TICKET,
        )
        add(recorder.skip("PT_ACCEPTANCE_ALLOW_WRITES is not 1: needs two real scopes"))
        recorder = CheckRecorder(
            "r2.limit_rejections",
            "oversized body, rate limit, spoofed forwarding headers, foreign Host",
            ticket=TICKET,
        )
        add(_host_and_header_probes(topology, recorder))
        return checks

    checks.extend(_business_loop(topology, fixtures, job_budget_s))
    checks.extend(_rejections(topology, fixtures))
    return checks


def _host_and_header_probes(topology: Topology, recorder: CheckRecorder) -> Check:
    """The transport rejections that need no writes; still a real observation."""
    observations: dict[str, Any] = {}
    try:
        foreign = request(
            topology, "/api/v1/health", headers={"Host": "invalid.example"}, timeout=15
        )
        observations["foreign_host"] = foreign.status
        forwarded = request(
            topology,
            "/api/v1/health",
            headers={"X-Forwarded-For": "203.0.113.9", "Forwarded": "for=203.0.113.9"},
            timeout=15,
        )
        observations["spoofed_forwarding"] = forwarded.status
    except TopologyUnavailable as error:
        return recorder.skip(f"topology unreachable: {error}")
    problems = []
    if observations["foreign_host"] not in (400, 421):
        problems.append(f"foreign Host returned {observations['foreign_host']}")
    # Caddy strips forwarding headers, so the API may legitimately answer 200;
    # a 400 ("Untrusted forwarding headers") is also acceptable evidence.
    if observations["spoofed_forwarding"] not in (200, 400, 403):
        problems.append(f"spoofed forwarding returned {observations['spoofed_forwarding']}")
    if problems:
        return _fail(recorder, "; ".join(problems), **observations)
    return recorder.pass_(
        "foreign Host rejected; spoofed forwarding headers did not grant identity",
        **observations,
    )


def _business_loop(topology: Topology, fixtures: Fixtures, job_budget_s: float) -> list[Check]:
    checks: list[Check] = []

    recorder = CheckRecorder(
        "r2.scope_a_single_apk",
        "draft -> POST /apk -> /start -> GET /jobs/{id} -> GET /jobs/{id}/report",
        ticket=TICKET,
    )
    scope_a: Scope | None = None
    try:
        scope_a = create_scope(topology, "acceptance-scope-a", "We never access the camera.")
    except TopologyUnavailable as error:
        checks.append(recorder.skip(f"scope A draft creation failed: {error}"))
    if scope_a is not None:
        upload = upload_apk(topology, scope_a, fixtures.single_apk)
        if upload.status != 200:
            checks.append(_fail(recorder, f"APK upload HTTP {upload.status}", status=upload.status))
        else:
            started = start_job(topology, scope_a)
            if started.status != 200 or not scope_a.job_id:
                checks.append(
                    _fail(recorder, f"start HTTP {started.status}", status=started.status)
                )
            else:
                outcome = poll_job(topology, scope_a, budget_s=job_budget_s)
                report = request(
                    topology, f"/api/v1/jobs/{scope_a.job_id}/report", token=scope_a.token
                )
                wrong_scope = _report_package(report) != fixtures.single_package
                if outcome["state"] != "SUCCEEDED":
                    checks.append(
                        _fail(
                            recorder,
                            f"job did not succeed: state={outcome['state']}",
                            state=outcome["state"],
                            trail=outcome["trail"],
                        )
                    )
                elif report.status != 200:
                    checks.append(
                        _fail(recorder, f"report HTTP {report.status}", status=report.status)
                    )
                elif wrong_scope:
                    checks.append(
                        _fail(
                            recorder,
                            "report belongs to a different package scope",
                            package=_report_package(report),
                        )
                    )
                else:
                    checks.append(
                        recorder.pass_(
                            f"single APK report readable; states={_states(outcome)}",
                            job_id=scope_a.job_id,
                            report_bytes=report.body_bytes,
                            scope=scope_a.as_dict(),
                            input_sha256=fixtures.single_sha256,
                        )
                    )

    recorder = CheckRecorder(
        "r2.policy_discovery_without_docker_socket",
        "draft -> POST /apk -> POST /sources/discover -> GET /drafts/{id}",
        ticket=TICKET,
    )
    scope_d: Scope | None = None
    try:
        scope_d = create_scope(
            topology, "acceptance-scope-discovery", "We never access the camera."
        )
    except TopologyUnavailable as error:
        checks.append(recorder.skip(f"discovery scope draft creation failed: {error}"))
    if scope_d is not None:
        upload = upload_apk(topology, scope_d, fixtures.single_apk)
        if upload.status != 200:
            checks.append(
                _fail(recorder, f"discovery upload HTTP {upload.status}", status=upload.status)
            )
        else:
            discovered = discover_policy_sources(topology, scope_d)
            if discovered.status == 503:
                checks.append(
                    _fail(
                        recorder,
                        "discovery returned 503; the control plane fell back to a local "
                        "container instead of the injected inspector",
                        status=discovered.status,
                        error=_error_code(discovered),
                    )
                )
            elif discovered.status != 200:
                checks.append(
                    _fail(recorder, f"discovery HTTP {discovered.status}", status=discovered.status)
                )
            else:
                document = discovered.json if isinstance(discovered.json, dict) else {}
                sources = document.get("sources") or []
                checks.append(
                    recorder.pass_(
                        f"policy discovery ran without a Docker socket; sources={len(sources)}",
                        status=discovered.status,
                        sources=len(sources),
                        scope=scope_d.as_dict(),
                    )
                )

    recorder = CheckRecorder(
        "r2.scope_b_base_and_splits",
        "draft -> POST /package-set -> /start -> GET /jobs/{id}/report",
        ticket=TICKET,
    )
    scope_b: Scope | None = None
    try:
        scope_b = create_scope(topology, "acceptance-scope-b", "We do not use camera or location.")
    except TopologyUnavailable as error:
        checks.append(recorder.skip(f"scope B draft creation failed: {error}"))
    if scope_b is not None:
        upload = upload_package_set(topology, scope_b, fixtures.package_set)
        if upload.status != 200:
            checks.append(
                _fail(recorder, f"package-set upload HTTP {upload.status}", status=upload.status)
            )
        else:
            started = start_job(topology, scope_b)
            if started.status != 200 or not scope_b.job_id:
                checks.append(
                    _fail(recorder, f"start HTTP {started.status}", status=started.status)
                )
            else:
                outcome = poll_job(topology, scope_b, budget_s=job_budget_s)
                report = request(
                    topology, f"/api/v1/jobs/{scope_b.job_id}/report", token=scope_b.token
                )
                if outcome["state"] != "SUCCEEDED":
                    checks.append(
                        _fail(
                            recorder,
                            f"package-set job did not succeed: state={outcome['state']}",
                            state=outcome["state"],
                            trail=outcome["trail"],
                        )
                    )
                elif report.status != 200:
                    checks.append(
                        _fail(recorder, f"report HTTP {report.status}", status=report.status)
                    )
                else:
                    summary = _package_set_summary(report)
                    if summary is None:
                        checks.append(_fail(recorder, "report carries no package_set summary"))
                    elif summary.get("split_count", 0) != 2 or set(
                        summary.get("split_names", [])
                    ) != {"config.en", "feature_camera"}:
                        checks.append(
                            _fail(
                                recorder,
                                "no split attributed in report",
                                split_count=summary.get("split_count"),
                            )
                        )
                    else:
                        checks.append(
                            recorder.pass_(
                                f"base+splits report has {summary.get('split_count')} splits",
                                job_id=scope_b.job_id,
                                split_count=summary.get("split_count"),
                                split_names=summary.get("split_names"),
                                report_bytes=report.body_bytes,
                                scope=scope_b.as_dict(),
                                input_sha256=fixtures.set_sha256,
                            )
                        )

    recorder = CheckRecorder(
        "r2.scope_isolation",
        "token A vs draft B and token B vs job A",
        ticket=TICKET,
    )
    if scope_a is None or scope_b is None or not (scope_a.job_id or scope_b.job_id):
        checks.append(recorder.skip("needs both scopes with a submitted job"))
        return checks
    read_b = request(topology, f"/api/v1/web/drafts/{scope_b.draft_id}", token=scope_a.token)
    job_read = request(topology, f"/api/v1/jobs/{scope_a.job_id}", token=scope_b.token)
    report_read = request(topology, f"/api/v1/jobs/{scope_a.job_id}/report", token=scope_b.token)
    delete_b = request(
        topology, f"/api/v1/web/drafts/{scope_b.draft_id}", method="DELETE", token=scope_a.token
    )
    unauth = request(topology, f"/api/v1/jobs/{scope_a.job_id}")
    problems = []
    if read_b.status != 403:
        problems.append(f"cross-scope draft read HTTP {read_b.status}")
    if job_read.status not in (403, 404):
        problems.append(f"cross-scope job read HTTP {job_read.status}")
    if report_read.status not in (403, 404):
        problems.append(f"cross-scope report read HTTP {report_read.status}")
    if delete_b.status != 403:
        problems.append(f"cross-scope delete HTTP {delete_b.status}")
    if unauth.status != 401:
        problems.append(f"unauthenticated job read HTTP {unauth.status}")
    detail = {
        "cross_scope_read": read_b.status,
        "cross_scope_job": job_read.status,
        "cross_scope_report": report_read.status,
        "cross_scope_delete": delete_b.status,
        "unauthenticated": unauth.status,
    }
    if problems:
        checks.append(_fail(recorder, "; ".join(problems), **detail))
    else:
        checks.append(
            recorder.pass_("all cross-scope and unauthenticated reads rejected", **detail)
        )
    import os
    from dataclasses import replace

    other_state = os.environ.get("PT_ACCEPTANCE_OTHER_LAB_STATE")
    recorder = CheckRecorder(
        "r2.cross_instance", "same capability against another instance", ticket=TICKET
    )
    if not other_state:
        checks.append(recorder.skip("a second owned laboratory is required"))
    else:
        from .provision import Laboratory

        other_lab = Laboratory(other_state)
        other = replace(
            topology,
            base_url=f"https://privacytrace.test:{other_lab.state['https_port']}",
            ca_file=other_lab.root / "public-ca.pem",
            instance_id=other_lab.state["instance_id"],
        )
        codes = [
            request(other, path, token=scope_a.token).status
            for path in (
                f"/api/v1/jobs/{scope_a.job_id}",
                f"/api/v1/jobs/{scope_a.job_id}/report",
                f"/api/v1/web/drafts/{scope_a.draft_id}",
            )
        ]
        if all(code in {403, 404} for code in codes) and other.instance_id != topology.instance_id:
            checks.append(
                recorder.pass_("cross-instance job, report and draft rejected", codes=codes)
            )
        else:
            checks.append(recorder.fail("cross-instance isolation failed", codes=codes))
    return checks


def _rejections(topology: Topology, fixtures: Fixtures) -> list[Check]:
    checks: list[Check] = []

    recorder = CheckRecorder(
        "r2.management_surface",
        "GET /api/v1/jobs, /api/v1/web/settings, /api/v1/jobs/{id} (no token)",
        ticket=TICKET,
    )
    try:
        listing = request(topology, "/api/v1/jobs")
        settings = request(topology, "/api/v1/web/settings")
        local_header = request(topology, "/api/v1/health", headers={"X-PrivacyTrace-Local": "1"})
    except TopologyUnavailable as error:
        checks.append(recorder.skip(f"topology unreachable: {error}"))
        return checks
    detail = {
        "jobs_listing": listing.status,
        "admin_settings": settings.status,
        "local_header": local_header.status,
    }
    problems = []
    if listing.status != 403:
        problems.append(f"jobs listing HTTP {listing.status}")
    if settings.status != 403:
        problems.append(f"admin settings HTTP {settings.status}")
    if local_header.status != 403:
        problems.append(f"spoofed local header HTTP {local_header.status}")
    checks.append(
        _fail(recorder, "; ".join(problems), **detail)
        if problems
        else recorder.pass_("management surface shielded", **detail)
    )

    recorder = CheckRecorder(
        "r2.oversize_rejection",
        "Expect:100-continue declared-length admission refusal (not streamed-body coverage)",
        ticket=TICKET,
    )
    try:
        from .topology import declared_length_rejection

        status = declared_length_rejection(topology, "/api/v1/web/drafts", 9 * 1024 * 1024)
    except TopologyUnavailable as error:
        checks.append(recorder.skip(f"topology unreachable: {error}"))
        return checks
    if status != 413:
        checks.append(_fail(recorder, f"oversize draft HTTP {status}", status=status))
    else:
        checks.append(
            recorder.pass_("oversize draft declared length rejected pre-parse", status=status)
        )

    recorder = CheckRecorder(
        "r2.invalid_split_dependency",
        "POST /package-set with base declaring isSplitRequired but no split",
        ticket=TICKET,
    )
    try:
        scope = create_scope(
            topology, "acceptance-reject", "Rejection scope.", "https://127.0.0.1:9/private"
        )
    except TopologyUnavailable as error:
        checks.append(recorder.skip(f"draft creation failed: {error}"))
        return checks
    builder = _builder()
    lone_base = builder.apk_bytes(
        package_name="org.privacytrace.acceptance.reject",
        version_code="1",
        manifest_options={"is_split_required": True},
    )
    rejected = upload_package_set(
        topology, scope, builder.package_set_archive(apks={"base.apk": lone_base})
    )
    code = _error_code(rejected)
    expected_codes = {"MISSING_REQUIRED_SPLIT", "INPUT_OR_VERSION_REJECTED"}
    if rejected.status in (400, 409) and code in expected_codes:
        checks.append(
            recorder.pass_(f"HTTP {rejected.status} {code}", status=rejected.status, code=code)
        )
    else:
        checks.append(
            _fail(recorder, f"HTTP {rejected.status} {code}", status=rejected.status, code=code)
        )
    recorder = CheckRecorder(
        "r2.authorized_oversize_upload",
        "Expect:100-continue, existing draft/token, 151MiB declared APK length",
        ticket=TICKET,
    )
    status = declared_length_rejection(
        topology, f"/api/v1/web/drafts/{scope.draft_id}/apk", 151 * 1024 * 1024, scope.token
    )
    checks.append(
        recorder.pass_("authorized oversized upload refused", status=status)
        if status == 413
        else recorder.fail("oversized upload was not refused with 413", status=status)
    )
    recorder = CheckRecorder(
        "r2.private_source_refusal", "fetch literal loopback policy URL", ticket=TICKET
    )
    current = request(topology, f"/api/v1/web/drafts/{scope.draft_id}", token=scope.token)
    fetched = request(
        topology,
        f"/api/v1/web/drafts/{scope.draft_id}/sources/policy/fetch",
        method="POST",
        token=scope.token,
        json_body={"revision": current.json["revision"]},
    )
    code = ((fetched.json or {}).get("sources") or [{}])[0].get("error_code")
    if fetched.status == 200 and code == "PUBLIC_URL_REQUIRED":
        checks.append(recorder.pass_("loopback source rejected before fetch", code=code))
    else:
        checks.append(
            recorder.fail("private source was not rejected", status=fetched.status, code=code)
        )

    recorder = CheckRecorder(
        "r2.rate_limit",
        "GET /api/v1/health repeated past PRIVACYTRACE_RATE_LIMIT",
        ticket=TICKET,
    )
    try:
        statuses = [
            request(
                topology,
                "/api/v1/health",
                timeout=10,
                headers={
                    "X-Forwarded-For": f"203.0.113.{index + 1}",
                    "Forwarded": f"for=203.0.113.{index + 1}",
                },
            ).status
            for index in range(70)
        ]
    except TopologyUnavailable as error:
        checks.append(recorder.skip(f"topology unreachable: {error}"))
        return checks
    limited = [item for item in statuses if item == 429]
    if limited:
        checks.append(recorder.pass_(f"{len(limited)}/70 responses were 429", limited=len(limited)))
    else:
        # A 60/min default budget with 70 requests over a warm connection may all
        # pass; state that instead of pretending.
        checks.append(
            recorder.not_tested(
                "no 429 within 70 sequential requests; use a lower "
                "PRIVACYTRACE_RATE_LIMIT or a burst client for this evidence"
            )
        )

    return checks


def _error_code(result: HttpResult) -> str:
    if isinstance(result.json, dict):
        return str(result.json.get("detail", ""))[:120]
    return ""


def _states(outcome: dict[str, Any]) -> str:
    return "->".join(entry["state"] for entry in outcome.get("trail", [])) or "unknown"


def _report_package(result: HttpResult) -> str:
    if result.status != 200 or not isinstance(result.json, dict):
        return ""
    sample = result.json.get("sample")
    if isinstance(sample, dict):
        return str(sample.get("package_name", ""))
    return ""


def _package_set_summary(result: HttpResult) -> dict[str, Any] | None:
    if result.status != 200 or not isinstance(result.json, dict):
        return None
    sample = result.json.get("sample")
    if not isinstance(sample, dict):
        return None
    summary = sample.get("package_set")
    return summary if isinstance(summary, dict) else None


